// Browser drives a real browser through agent-browser.
//
// The split with web_fetch has to be clear: web_fetch "fetches an HTML document", fast, cheap, no JS;
// browser "opens a browser", slow, expensive, but runs JavaScript, clicks, and sees what only appears
// after login. Picking wrong wastes money, so the description starts with "try web_fetch first".
//
// Why not write CDP by hand: the protocol is not the hard part — compressing the accessibility tree
// into a snapshot that fits the token budget and yielding reusable refs is. agent-browser already does
// that, and ships as a compiled binary rather than an npm package, so no Node is needed.
// Browser is stateless: the executable is resolved on every call (see Env.BrowserPath).
//
// Pinning it on the instance would fix it at startup, and a settings change would need a daemon
// restart.
type Browser struct{}

// browserSession is the session name reserved for us.
//
// "default" is not shared: agent-browser is also used by other programs (LobeHub), and colliding means
// both sides trample each other's tabs and cookies. It is closed after use, so logins do not persist
// across conversations.
const browserSession = "dcode"

// Per-action cap. navigate waits for the whole page, snapshot for the a11y tree.
const (
	browserNavTimeout    = 90 * time.Second
	browserActTimeout    = 60 * time.Second
	browserSnapMaxRunes  = 12000
	browserReadMaxRunes  = 12000
	browserShotDirEnvVar = "DUXCODE_BROWSER_SHOTS"
)

// ResolveAgentBrowser reports which executable would be used, and why when none is found.
//
// Order: the configured path → DUXCODE_AGENT_BROWSER → PATH. The configured path wins because the
// user picked it in settings and an environment variable must not override it; and when it is broken
// the reason is reported instead of silently falling back to PATH, which would look like "my path took
// effect" while another binary runs.
func ResolveAgentBrowser(configured string) (path, reason string) {
	if p := strings.TrimSpace(configured); p != "" {
		if isExecutable(p) {
			return p, ""
		}
		return "", "the given path is not executable: " + p
	}

	if p := strings.TrimSpace(os.Getenv("DUXCODE_AGENT_BROWSER")); p != "" {
		if isExecutable(p) {
			return p, ""
		}
		applog.Warnf("DUXCODE_AGENT_BROWSER points at a file that is not executable: %s", p)
	}

	if p, err := exec.LookPath("agent-browser"); err == nil {
		return p, ""
	}
	return "", "agent-browser was not found on PATH"
}

func isExecutable(p string) bool {
	st, err := os.Stat(p)
	return err == nil && !st.IsDir() && st.Mode()&0o111 != 0
}

