type browserArgs struct {
	Action      string `json:"action"`
	URL         string `json:"url"`
	Ref         string `json:"ref"`
	Text        string `json:"text"`
	Key         string `json:"key"`
	DY          int    `json:"dy"`
	Interactive bool   `json:"interactive"`
	Depth       int    `json:"depth"`
}

// Run implements Tool.
func (b *Browser) Run(ctx context.Context, raw string) (string, error) {
	env := EnvFrom(ctx)

	bin, reason := ResolveAgentBrowser(env.BrowserPath)
	if bin == "" {
		return "agent-browser not found: " + reason + ". Set its path in Settings → Tools, or put it on PATH.", nil
	}

	var in browserArgs
	if err := decodeArgs(raw, &in); err != nil {
		return err.Error(), nil
	}
	action := strings.ToLower(strings.TrimSpace(in.Action))

	switch action {
	case "navigate":
		if err := b.approve(ctx, env, "browser", "browser: open a URL",
			"go to "+in.URL+"\n(this is a separate browser instance and will not carry your usual logins)"); err != nil {
			return err.Error(), nil
		}
		data, err := cli(ctx, bin, browserNavTimeout, "open", in.URL)
		if err != nil {
			return "open failed: " + err.Error(), nil
		}
		return fmt.Sprintf("opened %s\ntitle: %s", str(data["url"]), str(data["title"])), nil

	case "snapshot":
		args := []string{"snapshot"}
		if in.Interactive {
			args = append(args, "-i")
		}
		if in.Depth > 0 {
			args = append(args, "-d", strconv.Itoa(in.Depth))
		}
		data, err := cli(ctx, bin, browserActTimeout, args...)
		if err != nil {
			return "could not get the page: " + err.Error(), nil
		}
		snap := str(data["snapshot"])
		if strings.TrimSpace(snap) == "" {
			return "this page has no readable structure (it may be blank). Try action=read.", nil
		}
		out := truncateRunes(snap, browserSnapMaxRunes)
		if refs, ok := data["refs"].(map[string]any); ok && len(refs) > 0 {
			out += fmt.Sprintf("\n\n(%d refs available; use them with click / fill)", len(refs))
		}
		return out, nil

	case "read":
		data, err := cli(ctx, bin, browserActTimeout, "read")
		if err != nil {
			return "read failed: " + err.Error(), nil
		}
		content := strings.TrimSpace(str(data["content"]))
		if content == "" {
			return "this page has no text content.", nil
		}
		return truncateRunes(content, browserReadMaxRunes), nil

	case "click":
		if in.Ref == "" {
			return "click needs a ref (take one with action=snapshot first).", nil
		}
		if err := b.approve(ctx, env, "browser", "browser: click",
			"click element "+in.Ref); err != nil {
			return err.Error(), nil
		}
		if _, err := cli(ctx, bin, browserActTimeout, "click", in.Ref); err != nil {
			return "click failed: " + err.Error() + " (a ref is only valid for the snapshot it came from; take a new snapshot)", nil
		}
		return "clicked " + in.Ref + ". The page may have changed; snapshot again if needed.", nil

	case "fill":
		if in.Ref == "" {
			return "fill needs a ref (take one with action=snapshot first).", nil
		}
		if err := b.approve(ctx, env, "browser", "browser: fill a field",
			"type into "+in.Ref+": "+in.Text); err != nil {
			return err.Error(), nil
		}
		if _, err := cli(ctx, bin, browserActTimeout, "fill", in.Ref, in.Text); err != nil {
			return "fill failed: " + err.Error(), nil
		}
		return "filled " + in.Ref + ". fill does not submit; press Enter or click a button to submit.", nil

	case "press":
		key := strings.TrimSpace(in.Key)
		if key == "" {
			return "press needs a key, e.g. Enter or Escape.", nil
		}
		if err := b.approve(ctx, env, "browser", "browser: press a key", "press "+key); err != nil {
			return err.Error(), nil
		}
		if _, err := cli(ctx, bin, browserActTimeout, "press", key); err != nil {
			return "press failed: " + err.Error(), nil
		}
		return "pressed " + key + ".", nil

	case "scroll":
		dy := in.DY
		dir := "down"
		if dy < 0 {
			dir, dy = "up", -dy
		}
		if dy == 0 {
			dy = 800
		}
		if _, err := cli(ctx, bin, browserActTimeout, "scroll", dir, strconv.Itoa(dy)); err != nil {
			return "scroll failed: " + err.Error(), nil
		}
		return fmt.Sprintf("scrolled %s by %d px. (scrolling does not change refs)", dir, dy), nil

	case "back":
		if _, err := cli(ctx, bin, browserActTimeout, "back"); err != nil {
			return "back failed: " + err.Error(), nil
		}
		return "went back one page.", nil

	case "screenshot":
		path := b.shotPath()
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return "could not create the directory: " + err.Error(), nil
		}
		if _, err := cli(ctx, bin, browserActTimeout, "screenshot", path); err != nil {
			return "screenshot failed: " + err.Error(), nil
		}
		return "screenshot saved to " + path, nil

	case "close":
		// With no browser open this fails, but that is not an error — the goal is already met.
		if _, err := cli(ctx, bin, browserActTimeout, "close"); err != nil {
			return "(the browser was not open)", nil
		}
		return "browser closed.", nil
	}

	return "unsupported action: " + action + " (available: navigate / snapshot / read / click / fill / press / scroll / back / screenshot / close)", nil
}

// approve goes through the normal approval flow with Kind "browser".
//
// Read-only actions (snapshot / read / screenshot / scroll / back / close) do not ask: they change
// nothing, and asking only breeds consent fatigue. Actions that send data out or navigate do.
func (b *Browser) approve(ctx context.Context, env Env, kind, title, detail string) error {
	return env.ask(ctx, Approval{
		Kind:   kind,
		Title:  title,
		Detail: detail,
	})
}

// cli runs agent-browser once and returns the data field of its JSON.
func cli(ctx context.Context, bin string, timeout time.Duration, args ...string) (map[string]any, error) {
	ctx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()

	full := append([]string{"--json", "--session", browserSession}, args...)
	cmd := exec.CommandContext(ctx, bin, full...)
	// Its own process group: when the CLI is killed on timeout, no child is left sitting on a page.
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	cmd.Cancel = func() error {
		if cmd.Process == nil {
			return nil
		}
		return syscall.Kill(-cmd.Process.Pid, syscall.SIGKILL)
	}

	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr

	err := cmd.Run()
	if errors.Is(ctx.Err(), context.DeadlineExceeded) {
		return nil, fmt.Errorf("no response after %s", timeout)
	}

	raw := bytes.TrimSpace(stdout.Bytes())
	if len(raw) == 0 {
		// On failure it may print nothing and only write the reason to stderr.
		msg := strings.TrimSpace(stderr.String())
		if msg == "" && err != nil {
			msg = err.Error()
		}
		if msg == "" {
			msg = "no output"
		}
		return nil, errors.New(firstLines(msg, 3))
	}

	var res struct {
		Success bool           `json:"success"`
		Data    map[string]any `json:"data"`
		Error   *string        `json:"error"`
	}
	if json.Unmarshal(raw, &res) != nil {
		// A few commands print plain text. Returning it as-is beats pretending parsing failed.
		return map[string]any{"raw": string(raw)}, nil
	}
	if !res.Success {
		if res.Error != nil && strings.TrimSpace(*res.Error) != "" {
			return nil, errors.New(*res.Error)
		}
		return nil, errors.New("reported failure without a message")
	}
	return res.Data, nil
}

// shotPath gives screenshots a durable location (XDG data, not /tmp).
func (b *Browser) shotPath() string {
	dir := strings.TrimSpace(os.Getenv(browserShotDirEnvVar))
	if dir == "" {
		base := os.Getenv("XDG_DATA_HOME")
		if base == "" {
			home, _ := os.UserHomeDir()
			base = filepath.Join(home, ".local", "share")
		}
		dir = filepath.Join(base, "dcode", "browser")
	}
	return filepath.Join(dir, "shot-"+time.Now().Format("20060102-150405")+".png")
}

// str reads a value safely: numbers in JSON may be used as strings too.
func str(v any) string {
	switch x := v.(type) {
	case nil:
		return ""
	case string:
		return x
	case float64:
		if x == float64(int64(x)) {
			return strconv.FormatInt(int64(x), 10)
		}
		return strconv.FormatFloat(x, 'f', -1, 64)
	case bool:
		return strconv.FormatBool(x)
	}
	return fmt.Sprint(v)
}

// truncateRunes truncates but keeps the head — a page's point is almost always at the front.
func truncateRunes(s string, limit int) string {
	r := []rune(s)
	if len(r) <= limit {
		return s
	}
	return string(r[:limit]) + fmt.Sprintf("\n… (truncated, %d characters originally)", len(r))
}

// firstLines takes the first n lines; an error message should not dump a stack trace on the model.
func firstLines(s string, n int) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	if len(lines) <= n {
		return strings.TrimSpace(s)
	}
	return strings.Join(lines[:n], "\n")
}
